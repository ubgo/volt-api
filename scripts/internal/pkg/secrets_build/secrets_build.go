const (
	prodKeyFilesDir        = "../_keys"
	prodKeyFilesSuffix     = "_prod"
	secretsProdFile        = "../.github/.secrets.prod"
	secretsFile            = "../.github/.secrets"
	deployYamlFile         = "../.github/workflows/deploy.yml"
	deployYamlTemplateFile = "../.github/workflows/deploy.yml.gotmpl"
	envProdFile            = "../.env.prod"
)

func GetSecretFilePath() string {
	return secretsFile
}

func BuldAndUpdateSecrets() {
	// read default github secrets
	secrets := ReadSecretsFile(secretsProdFile)

	// read prod key files and add to secrets
	prodKeyFiles := ReadProdKeyFiles()
	for _, prodKeyFile := range prodKeyFiles {
		secrets = append(secrets, Secret{
			Key:   prodKeyFile.EnvVarName,
			Value: prodKeyFile.Content,
		})
	}

	secrets = append(secrets, Secret{
		Key:   "ENV_PROD_B64",
		Value: readAndEncodeEnvProd(),
	})

	WriteNewSecrets(secrets)
	CreateGithubDeployYaml()
}

func readAndEncodeEnvProd() string {
	envProdPath := envProdFile
	envContent, err := os.ReadFile(envProdPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	return base64.StdEncoding.EncodeToString(envContent)
}

func CreateGithubDeployYaml() {
	prodKeyFiles := ReadProdKeyFiles()
	envString := ""

	/*
	  # NEVER REMOVE THIS COMMENT
	   echo "==> Writing _keys files..."
	   echo "${GITHUB_APP_KEY_B64}" | base64 -d > ${DEPLOY_PATH}/_keys/github-app-private-key.pem
	   chmod 600 ${DEPLOY_PATH}/_keys/github-app-private-key.pem
	   chown -R 1000:1000 ${DEPLOY_PATH}/_keys
	*/
	shScript := ""

	//envs: DEPLOY_PATH,IMAGE,CONTAINER,GHCR_PAT,REGISTRY,REPO_OWNER,ENV_PROD_B64,GITHUB_APP_KEY_B64
	var envVarNames []string

	spaceenv := ""
	spaceenv_sh := ""
	spacesh_default := "            "

	for i, prodKeyFile := range prodKeyFiles {

		if i > 0 {
			spaceenv = "          "
			spaceenv_sh = spacesh_default
		}

		// Add env var: GITHUB_2024_KEY_B64: ${{ secrets.GITHUB_2024_KEY }}
		envString += spaceenv + prodKeyFile.EnvVarName + ": ${{ secrets." + prodKeyFile.EnvVarName + " }}\n"

		// Add to envs list for the ssh-action
		envVarNames = append(envVarNames, prodKeyFile.EnvVarName)

		// Generate script to decode and save with unified filename
		shScript += spaceenv_sh + "echo \"${" + prodKeyFile.EnvVarName + "}\" | base64 -d > ${DEPLOY_PATH}/_keys/" + prodKeyFile.OriginalFileName + "\n"
	}

	// Add chown once at the end (more efficient)
	if len(prodKeyFiles) > 0 {
		shScript += spacesh_default + "chmod 600 ${DEPLOY_PATH}/_keys/*\n"
		shScript += spacesh_default + "chown -R 1000:1000 ${DEPLOY_PATH}/_keys\n"
	}

	envString = strings.TrimRight(envString, "\n")
	shScript = strings.TrimRight(shScript, "\n")

	// Build envs list for ssh-action (comma-separated)
	envsList := "DEPLOY_PATH,IMAGE,CONTAINER,GHCR_PAT,REGISTRY,REPO_OWNER,ENV_PROD_B64"
	if len(envVarNames) > 0 {
		envsList += "," + strings.Join(envVarNames, ",")
	}

	// Read the template file
	templatePath := deployYamlTemplateFile
	templateContent, err := os.ReadFile(templatePath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading template file: %v\n", err)
		os.Exit(1)
	}

	// Parse the template with custom delimiters to avoid conflicts with GitHub Actions ${{ }} syntax
	tmpl, err := template.New("deploy").Delims("[[", "]]").Parse(string(templateContent))
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing template: %v\n", err)
		os.Exit(1)
	}

	// Prepare template data
	data := struct {
		ENV_STRING string
		SH_SCRIPT  string
		ENVS_LIST  string
	}{
		ENV_STRING: envString,
		SH_SCRIPT:  shScript,
		ENVS_LIST:  envsList,
	}

	// Execute the template
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		fmt.Fprintf(os.Stderr, "Error executing template: %v\n", err)
		os.Exit(1)
	}

	// Write the output file
	outputPath := deployYamlFile
	if err := os.WriteFile(outputPath, buf.Bytes(), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing deploy.yml: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Successfully generated %s\n", outputPath)
}

type Secret struct {
	Key   string `json:"key"`
	Value string `json:"value"`
}

func WriteNewSecrets(secrets []Secret) {
	secretsStr := "# Code generated by the secrets_build.go script., DO NOT EDIT\n\n"
	for _, secret := range secrets {
		secretsStr += secret.Key + "=\"" + secret.Value + "\"\n"
	}
	if err := os.WriteFile(secretsFile, []byte(secretsStr), 0644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func ReadSecretsFile(path string) []Secret {
	secrets, err := godotenv.Read(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var prodSecrets []Secret
	for key, value := range secrets {
		prodSecrets = append(prodSecrets, Secret{Key: key, Value: value})
	}
	return prodSecrets
}

type ProdKeyFile struct {
	// FileName         string `json:"fileName"`         // github_2024_prod (unified name without extension)
	// FileExt          string `json:"fileExt"`          // .pem
	FileNameKey      string `json:"fileNameKey"`      // GITHUB_2024_KEY (for secret name)
	EnvVarName       string `json:"envVarName"`       // GITHUB_2024_KEY_B64 (for env var)
	OriginalFileName string `json:"originalFileName"` // github_2024_xyz.prod.pem (original)
	// UnifiedFileName  string `json:"unifiedFileName"`  // github_2024_prod.pem (for Docker)
	Content string `json:"content"` // base64 encoded content
}

// getNameWithoutExtension returns the filename without its extension.
func getNameWithoutExtension(fileName string) string {
	extension := filepath.Ext(fileName)
	if extension == "" {
		return fileName
	}
	return fileName[:len(fileName)-len(extension)]
}

func ReadProdKeyFiles() []ProdKeyFile {
	files, err := os.ReadDir(prodKeyFilesDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var prodKeyFiles []ProdKeyFile
	for _, file := range files {
		if file.IsDir() {
			continue
		}

		// file should end with .prod.xx (e.g., github_2024_xyz.prod.pem)
		if !strings.Contains(file.Name(), prodKeyFilesSuffix+".") {
			continue
		}

		// Read the file content
		content, err := os.ReadFile(filepath.Join(prodKeyFilesDir, file.Name()))
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}

		fileBaseName := getNameWithoutExtension(file.Name())

		// Generate secret key name: uppercase and add _KEY suffix
		// e.g., "github_2024_xyz" -> "GITHUB_2024_XYZ" -> "GITHUB_2024_XYZ_KEY"
		// But we want to use the unified name for consistency
		secretKeyBase := strings.ToUpper(strings.ReplaceAll(fileBaseName, "-", "_"))
		secretKeyBase = strings.ReplaceAll(secretKeyBase, " ", "_")
		fileNameKey := secretKeyBase + "_KEY" // e.g., "GITHUB_2024_KEY"
		envVarName := fileNameKey + "_B64"    // e.g., "GITHUB_2024_KEY_B64"

		// Base64 encode the content
		contentBase64 := base64.StdEncoding.EncodeToString(content)

		prodKeyFiles = append(prodKeyFiles, ProdKeyFile{
			// FileName:         fileBaseName,
			// FileExt:          ext,
			FileNameKey:      fileNameKey,
			EnvVarName:       envVarName,
			OriginalFileName: file.Name(),
			Content:          contentBase64,
		})
	}

	return prodKeyFiles
}

func PushSecretsToGithub() {
	secrets := ReadSecretsFile(secretsFile)
	for _, secret := range secrets {
		pushSecret(secret.Key, secret.Value)
		fmt.Println("Pushed secret: ", secret.Key)
	}
}

func pushSecret(key, value string) error {
	cmd := exec.Command("gh", "secret", "set", key)
	cmd.Stdin = strings.NewReader(value)
	return cmd.Run()
}

// GetExpectedSecretNames returns the list of secret names that should exist
// (same set as BuldAndUpdateSecrets would write to .github/.secrets).
func GetExpectedSecretNames() []string {
	names := []string{}
	secrets := ReadSecretsFile(secretsProdFile)
	for _, s := range secrets {
		names = append(names, s.Key)
	}
	prodKeyFiles := ReadProdKeyFiles()
	for _, f := range prodKeyFiles {
		names = append(names, f.EnvVarName)
	}
	names = append(names, "ENV_PROD_B64")
	return names
}

// ghSecretListItem is used to parse "gh secret list --json name" output.
type ghSecretListItem struct {
	Name string `json:"name"`
}

// ListGithubSecrets returns the names of repository secrets currently on GitHub.
func ListGithubSecrets() ([]string, error) {
	cmd := exec.Command("gh", "secret", "list", "--json", "name")
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("gh secret list: %w", err)
	}
	var items []ghSecretListItem
	if err := json.Unmarshal(out, &items); err != nil {
		return nil, fmt.Errorf("parse gh secret list output: %w", err)
	}
	names := make([]string, 0, len(items))
	for _, item := range items {
		names = append(names, item.Name)
	}
	return names, nil
}

// DeleteGithubSecret removes a repository secret from GitHub.
func DeleteGithubSecret(name string) error {
	cmd := exec.Command("gh", "secret", "delete", name)
	cmd.Stdin = strings.NewReader("y\n") // confirm deletion
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("gh secret delete %s: %w: %s", name, err, string(out))
	}
	return nil
}

// expectedSet returns a set of expected secret names for quick lookup.
func expectedSet(expected []string) map[string]struct{} {
	m := make(map[string]struct{}, len(expected))
	for _, name := range expected {
		m[name] = struct{}{}
	}
	return m
}

// CleanNonExistingSecrets removes from GitHub any repository secret that is not
// in the expected set (from .secrets.prod, prod key files, and ENV_PROD_B64).
func CleanNonExistingSecrets() {
	expected := GetExpectedSecretNames()
	allowed := expectedSet(expected)
	current, err := ListGithubSecrets()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Failed to list GitHub secrets: %v\n", err)
		os.Exit(1)
	}
	var removed int
	for _, name := range current {
		if _, ok := allowed[name]; ok {
			continue
		}
		if err := DeleteGithubSecret(name); err != nil {
			fmt.Fprintf(os.Stderr, "Failed to delete secret %q: %v\n", name, err)
			os.Exit(1)
		}
		fmt.Println("Removed secret:", name)
		removed++
	}
	if removed == 0 {
		fmt.Println("No orphan secrets to remove.")
	} else {
		fmt.Printf("Removed %d orphan secret(s).\n", removed)
	}
}
